// Package docgen renders the command reference (docs/commands.md and
// docs/reference/*.md) from the cobra command tree, so the docs carry the
// same text as --help and cannot drift from it.
package docgen

import (
	"bytes"
	"cmp"
	"fmt"
	"math"
	"regexp"
	"slices"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"

	cmdutil "github.com/verda-cloud/verda-cli/internal/verda-cli/cmd/util"
)

const (
	// IndexFile is the grouped command index, relative to the docs dir.
	IndexFile = "commands.md"
	// ReferenceDir holds one page per top-level command, relative to the docs dir.
	ReferenceDir = "reference"

	generatedHeader = "<!-- Code generated by make docs at each release; DO NOT EDIT. -->\n\n"
	ungroupedTitle  = "Additional Commands"
	textLang        = "text"
	tagsURL         = "https://github.com/verda-cloud/verda-cli/tags"

	indexTitle = "Command Reference"
	indexIntro = `Every Verda CLI command, grouped as in ` + "`verda --help`" + `. Each entry links to its reference page with
usage, flags and examples. The pages are generated from the CLI's own help text.

See also: [Authentication](guides/authentication.md) · [Scripting and agent mode](guides/scripting.md) ·
[Agent error format](agent-errors.md) · [AI skills](ai-skills.md)

`

	globalFlagsNote = "Global flags such as `--output`, `--agent` and `--debug` work with every command: " +
		"see [Global Flags](../" + IndexFile + "#global-flags).\n"
)

var releaseVersion = regexp.MustCompile(`^v\d+\.\d+\.\d+$`)

// Generate returns the rendered docs keyed by slash-separated path relative
// to the docs dir. Hidden, deprecated and help commands are left out. version
// is the release the docs describe (vX.Y.Z); every page names it.
func Generate(root *cobra.Command, version string) (map[string][]byte, error) {
	if !releaseVersion.MatchString(version) {
		return nil, fmt.Errorf("version %q: want vX.Y.Z", version)
	}
	files := map[string][]byte{IndexFile: renderIndex(root, version)}
	for _, top := range root.Commands() {
		if top.IsAvailableCommand() {
			files[pagePath(top)] = renderPage(root, top, version)
		}
	}
	// Styled text would leak terminal escapes into Markdown.
	for name, b := range files {
		if bytes.ContainsRune(b, '\x1b') {
			return nil, fmt.Errorf("%s: ANSI escape in command help text", name)
		}
	}
	return files, nil
}

type commandGroup struct {
	title    string
	commands []*cobra.Command
}

// groupedCommands: root.Groups() order; within a group, declaration order as
// in --help, then any undeclared commands by name.
func groupedCommands(root *cobra.Command) []commandGroup {
	groups := make([]commandGroup, 0, len(root.Groups())+1)
	byID := map[string]int{}
	for _, g := range root.Groups() {
		byID[g.ID] = len(groups)
		groups = append(groups, commandGroup{title: strings.TrimSuffix(g.Title, ":")})
	}
	ungrouped := commandGroup{title: ungroupedTitle}
	for _, c := range root.Commands() {
		if !c.IsAvailableCommand() {
			continue
		}
		if i, ok := byID[c.GroupID]; ok {
			groups[i].commands = append(groups[i].commands, c)
		} else {
			ungrouped.commands = append(ungrouped.commands, c)
		}
	}
	if len(ungrouped.commands) > 0 {
		groups = append(groups, ungrouped)
	}
	for i := range groups {
		slices.SortStableFunc(groups[i].commands, func(a, b *cobra.Command) int {
			return cmp.Compare(declarationRank(a), declarationRank(b))
		})
	}
	return groups
}

func declarationRank(c *cobra.Command) int {
	if rank, ok := cmdutil.DeclarationOrder(c); ok {
		return rank
	}
	return math.MaxInt
}

func renderIndex(root *cobra.Command, version string) []byte {
	var b strings.Builder
	writeTitle(&b, indexTitle, version)
	b.WriteString(indexIntro)
	for _, g := range groupedCommands(root) {
		if len(g.commands) == 0 {
			continue
		}
		fmt.Fprintf(&b, "## %s\n\n| Command | Description |\n|---------|-------------|\n", g.title)
		for _, top := range g.commands {
			page := pagePath(top)
			fmt.Fprintf(&b, "| [`%s`](%s)%s | %s |\n", top.CommandPath(), page, cmdutil.TagSuffix(top), tableCell(top.Short))
			for _, c := range descendants(top) {
				fmt.Fprintf(&b, "| [`%s`](%s#%s) | %s |\n", c.CommandPath(), page, anchor(c), tableCell(c.Short))
			}
		}
		b.WriteString("\n")
	}
	b.WriteString("## Global Flags\n\n")
	writeFence(&b, textLang, visibleFlags(root.PersistentFlags(), nil).FlagUsages())
	return []byte(strings.TrimRight(b.String(), "\n") + "\n")
}

// writeTitle: the version line sits under every H1, since readers often land on a page directly.
func writeTitle(b *strings.Builder, title, version string) {
	b.WriteString(generatedHeader)
	fmt.Fprintf(b, "# %s\n\n> Verda CLI **%s** · [other versions](%s)\n\n", title, version, tagsURL)
}

func renderPage(root, top *cobra.Command, version string) []byte {
	var b strings.Builder
	writeTitle(&b, top.CommandPath()+cmdutil.TagSuffix(top), version)
	writeCommand(&b, root, top)
	subs := descendants(top)
	if len(subs) > 0 {
		b.WriteString("Subcommands:\n\n")
		for _, c := range subs {
			fmt.Fprintf(&b, "- [`%s`](#%s): %s\n", c.CommandPath(), anchor(c), escapeText(c.Short))
		}
		b.WriteString("\n")
	}
	for _, c := range subs {
		fmt.Fprintf(&b, "## %s\n\n", c.CommandPath())
		writeCommand(&b, root, c)
	}
	b.WriteString("---\n\n")
	b.WriteString(globalFlagsNote)
	return []byte(strings.TrimRight(b.String(), "\n") + "\n")
}

func writeCommand(b *strings.Builder, root, c *cobra.Command) {
	// LocalFlags/InheritedFlags merge parent persistent flags into c; UseLine's
	// "[flags]" depends on that merge, so resolve flags before rendering usage.
	local := visibleFlags(c.LocalFlags(), nil)
	// By identity: a group flag may shadow a global flag of the same name.
	notGlobal := func(f *pflag.Flag) bool { return root.PersistentFlags().Lookup(f.Name) != f }
	inherited := visibleFlags(c.InheritedFlags(), notGlobal)

	b.WriteString(escapeText(c.Short) + "\n\n")
	if c.Long != "" {
		b.WriteString(renderLong(c.Long))
	}
	// Group commands' Run only prints help; their subcommand list is the usage.
	if c.Runnable() && !c.HasAvailableSubCommands() {
		b.WriteString("**Usage**\n\n")
		writeFence(b, textLang, c.UseLine())
	}
	if len(c.Aliases) > 0 {
		b.WriteString("Aliases: `" + strings.Join(c.Aliases, "`, `") + "`\n\n")
	}
	if local.HasAvailableFlags() {
		b.WriteString("**Flags**\n\n")
		writeFence(b, textLang, local.FlagUsages())
	}
	if inherited.HasAvailableFlags() {
		b.WriteString("**Inherited flags**\n\n")
		writeFence(b, textLang, inherited.FlagUsages())
	}
	if c.Example != "" {
		b.WriteString("**Examples**\n\n")
		writeFence(b, "bash", dedent(c.Example))
	}
}

// renderLong keeps prose as Markdown paragraphs and fences each run of
// indented lines, which GFM would otherwise merge into the paragraph.
func renderLong(s string) string {
	lines := strings.Split(strings.TrimSpace(s), "\n")
	var b strings.Builder
	for i := 0; i < len(lines); {
		j := i + 1
		if isIndented(lines[i]) {
			for j < len(lines) && continuesCode(lines, j) {
				j++
			}
			writeFence(&b, textLang, dedent(strings.Join(lines[i:j], "\n")))
		} else {
			for j < len(lines) && !isIndented(lines[j]) {
				j++
			}
			writeProse(&b, lines[i:j])
		}
		i = j
	}
	return b.String()
}

// continuesCode: an indented line, or a blank line followed by more indented ones.
func continuesCode(lines []string, j int) bool {
	for ; j < len(lines); j++ {
		if strings.TrimSpace(lines[j]) != "" {
			return isIndented(lines[j])
		}
	}
	return false
}

func writeProse(b *strings.Builder, lines []string) {
	text := strings.Trim(strings.Join(lines, "\n"), "\n ")
	for line := range strings.SplitSeq(text, "\n") {
		// Trailing double spaces would become hard line breaks.
		line = escapeText(strings.TrimRight(line, " \t"))
		if strings.HasPrefix(line, "#") {
			line = `\` + line
		}
		b.WriteString(line + "\n")
	}
	b.WriteString("\n")
}

func isIndented(line string) bool {
	return line != "" && (line[0] == ' ' || line[0] == '\t')
}

func dedent(s string) string {
	lines := strings.Split(strings.Trim(s, "\n"), "\n")
	minIndent := -1
	for _, line := range lines {
		if strings.TrimSpace(line) == "" {
			continue
		}
		if n := len(line) - len(strings.TrimLeft(line, " \t")); minIndent < 0 || n < minIndent {
			minIndent = n
		}
	}
	for i, line := range lines {
		switch {
		case strings.TrimSpace(line) == "":
			lines[i] = ""
		case minIndent > 0:
			lines[i] = line[minIndent:]
		}
	}
	return strings.Join(lines, "\n")
}

// escapeText escapes HTML and emphasis characters outside `code spans`, so
// placeholders like <name> survive GFM rendering.
func escapeText(s string) string {
	parts := strings.Split(s, "`")
	closed := len(parts)%2 == 1
	r := strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;", "*", `\*`)
	for i := range parts {
		inCode := i%2 == 1 && (closed || i < len(parts)-1)
		if !inCode {
			parts[i] = r.Replace(parts[i])
		}
	}
	return strings.Join(parts, "`")
}

// tableCell additionally escapes pipes, which split GFM cells even inside code spans.
func tableCell(s string) string {
	return strings.ReplaceAll(escapeText(s), "|", `\|`)
}

func writeFence(b *strings.Builder, lang, body string) {
	fence := "```"
	if strings.Contains(body, fence) {
		fence = "~~~~"
	}
	lines := strings.Split(strings.TrimRight(body, " \n"), "\n")
	for i := range lines {
		lines[i] = strings.TrimRight(lines[i], " \t")
	}
	b.WriteString(fence + lang + "\n" + strings.Join(lines, "\n") + "\n" + fence + "\n\n")
}

// visibleFlags copies the non-hidden flags (minus help) that pass keep.
func visibleFlags(fs *pflag.FlagSet, keep func(*pflag.Flag) bool) *pflag.FlagSet {
	out := pflag.NewFlagSet("", pflag.ContinueOnError)
	fs.VisitAll(func(f *pflag.Flag) {
		if !f.Hidden && f.Name != "help" && (keep == nil || keep(f)) {
			out.AddFlag(f)
		}
	})
	return out
}

// descendants lists available subcommands depth-first, sorted by name.
func descendants(c *cobra.Command) []*cobra.Command {
	var out []*cobra.Command
	for _, sub := range c.Commands() {
		if sub.IsAvailableCommand() {
			out = append(out, sub)
			out = append(out, descendants(sub)...)
		}
	}
	return out
}

func pagePath(top *cobra.Command) string {
	return ReferenceDir + "/" + top.Name() + ".md"
}

// anchor matches GitHub's heading slug for a "## verda <path>" heading.
func anchor(c *cobra.Command) string {
	return strings.ReplaceAll(strings.ToLower(c.CommandPath()), " ", "-")
}
